/**
 * system-msg.js — 认出「这不是人说的话」，让机器人别去回它。
 *
 * 为什么需要（用户报的「制作过滤系统消息」，起因是真实日志）：
 *   轮询跑起来之后，日志里有 3 条回复是在回 QQ 自己的提示：
 *       回复 [乐音] "临时会话"                       → "示例昵称"
 *       回复 [乐音] "该用户通过“临时会话谨防兼职刷单、游戏交易、投资荐股、
 *                     色情招嫖、仿冒公检法及客服人员的网络骗局，如有资金往来请谨慎操作。"
 *       回复 [乐音] "该用户通过“"（被截断的同一句）
 *   那不是人说的话，回它既没意义，又一眼就能看出这边是个机器人。
 *
 * 设计原则（两条，都别违反）：
 *   1. **规则要有实测依据**，不能拍脑袋。下面每条都注明是在哪见到的。
 *      （有用的反面例子：夹具里出现的「语音通话」「视频通话」「红包」其实是
 *       **标题栏工具栏按钮**的文案，不是聊天消息 —— 照它们写规则会误伤。）
 *   2. **宁可不筛，也别误伤真人**。像「图片」「表情」「文件」这种，
 *      真人完全可能就发这两个字当消息；所以只筛**带方括号的占位形态**（`[图片]`），
 *      裸词一律不管。群通知也要求"整句没有逗号句号"（通知是机器拼的，人说话一般带标点）。
 *
 * 筛掉的不是"没价值的内容"，而是"**回它很奇怪的东西**"：QQ 通知、分隔线、
 * 卡片（红包/转账）、拍一拍/戳一戳这类动作提示。
 */

/**
 * 内置规则。顺序无所谓（只取第一条命中的名字做日志）。
 *
 * 每条都要能回答："这个形态是**机器拼出来的**，还是人可能自己打出来的？"
 */
export const SYSTEM_RULES = [
  // ---- 实测（真实日志，2026-10-06 轮询那轮）----
  {
    name: '临时会话提示',
    re: /^临时会话$/,
    why: '非好友私聊时 QQ 插的分隔提示',
  },
  {
    name: '防骗提示',
    // 两个都命中同一条消息的全文/残句：QQ 会把这条长通知渲染成多段，
    // 我们可能只读到前半段（实测读到过只剩「该用户通过“」）。
    re: /(该用户通过|谨防兼职刷单|网络骗局|如有资金往来请谨慎操作)/,
    why: '临时会话的防诈骗长通知（实测被当成消息回过）',
  },

  // ---- 实测（夹具 uia-sessions.json 的会话预览里就有）----
  {
    name: '群成员变动',
    // 锚到整句、且要求**没有标点**：QQ 的通知是拼出来的（「XXX 加入了群聊」），
    // 而真人说「我昨天加入了群聊，你呢」带标点 → 不误伤。
    re: /^[^，。！？；,.!?;]{0,24}(加入了群聊|加入了本群|移出群聊|退出群聊|加入了群)$/,
    why: '「你已被移出群聊」这类通知（夹具里抓到过）',
  },
  {
    name: '群管理/群设置通知',
    re: /^[^，。！？；,.!?;]{0,30}(修改群名为|群公告|成为了群管理员|被设为管理员|被取消管理员|开启了全员禁言|关闭了全员禁言)/,
    why: '同一类机器拼的通知',
  },

  // ---- 好友关系类（换个人聊就成立的系统话术）----
  {
    name: '好友关系提示',
    re: /^(以上是打招呼的内容|对方已不是你的好友|你已添加了.{1,24}现在可以开始聊天了|.{1,24}开启了朋友验证|.{1,24}拒绝接收消息)/,
    why: '加好友/删好友时 QQ 说的话',
  },

  // ---- 动作与卡片 ----
  {
    name: '撤回提示',
    re: /^[^，。！？；,.!?;]{0,24}撤回了一条消息$/,
    why: '撤回通知（消息本体已经没了，回它没有对象）',
  },
  {
    name: '通话记录',
    re: /^(语音通话|视频通话)$/,
    why: '通话记录（注意：工具栏按钮也叫这个名字，但那些不是聊天消息，不会走到这里）',
  },
  {
    name: '戳一戳/拍一拍',
    // ⚠ 加了"整句不许带标点"这一条：实测「你拍了拍我的头？」被误伤过 ——
    //   那是人在问话，得回。QQ 自己的动作提示是拼出来的，没有问号感叹号。
    re: /^[^，。！？；,.!?;]{0,20}(拍了拍|戳了戳)[^，。！？；,.!?;]{0,10}$/,
    why: '动作提示，不是人打的字',
  },
  {
    name: '卡片消息',
    // ⚠ 只认**带方括号**的占位形态。裸的「图片」「文件」「红包」不筛 ——
    //   真人真的会只发「图片」两个字（实测用户就爱这么干）。
    re: /^\[(图片|视频|语音|文件|表情|位置|名片|动画表情|音乐)\]$/,
    why: 'QQ 对媒体消息的占位渲染，正文读不到，回它等于答非所问',
  },
  {
    name: '时间分隔线',
    re: /^\d{1,2}:\d{2}$/,
    why: '解析层本来就会丢，这里再兜一层（OCR 路线偶尔漏过来）',
  },
];

/**
 * 这条消息是不是"系统消息"？
 *
 * @param {string} text 消息正文
 * @param {object} cfg  读 `trigger.ignoreSystemMessages`（默认开）和
 *                      `trigger.systemPatterns`（用户自己加的额外规则）
 * @returns {{system:boolean, name?:string, why?:string, from?:'builtin'|'config'}}
 */
export function classifySystemMessage(text, cfg) {
  const t = String(text ?? '').trim();
  if (!t) return { system: false };

  // 总开关：关掉就一律不筛（有人就是想让它连系统提示也回一句）
  if (cfg?.trigger?.ignoreSystemMessages === false) return { system: false };

  for (const r of SYSTEM_RULES) {
    if (r.re.test(t)) return { system: true, name: r.name, why: r.why, from: 'builtin' };
  }

  // 用户自己加的：一条一行（或逗号分隔），写正则也行、写普通词也行 ——
  // 普通词按"包含"匹配，正则写错了就退回按包含匹配（和 fallback 的规则同一套宽容策略）。
  const extra = cfg?.trigger?.systemPatterns;
  if (Array.isArray(extra)) {
    for (const raw of extra) {
      const s = String(raw ?? '').trim();
      if (!s) continue;
      let hit = false;
      try { hit = new RegExp(s, 'i').test(t); } catch { hit = t.includes(s); }
      if (hit) return { system: true, name: s, why: '你在配置里加的系统消息规则', from: 'config' };
    }
  }

  return { system: false };
}

/** 只要一个布尔值时用它（调用方大多只关心"筛不筛"）。 */
export function isSystemMessage(text, cfg) {
  return classifySystemMessage(text, cfg).system;
}

/** 给控制台/文档用：内置规则的名字与理由。 */
export function describeSystemRules() {
  return SYSTEM_RULES.map((r) => ({ name: r.name, why: r.why }));
}
